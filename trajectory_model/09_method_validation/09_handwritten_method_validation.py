def result_edge_table(
    nodes_df,
    graph,
    method,
    edges,
):
    name_by_index = dict(
        zip(
            nodes_df[
                "node_index"
            ],
            nodes_df[
                "node"
            ],
        )
    )

    rows = []

    for u, v in sorted(
        edges
    ):

        rows.append(
            {
                "method":
                    method,
                "node_u_index":
                    int(
                        u
                    ),
                "node_v_index":
                    int(
                        v
                    ),
                "node_u":
                    name_by_index[
                        int(
                            u
                        )
                    ],
                "node_v":
                    name_by_index[
                        int(
                            v
                        )
                    ],
                "weight":
                    edge_weight(
                        graph,
                        (
                            u,
                            v,
                        ),
                    ),
            }
        )

    return pd.DataFrame(
        rows
    )


def expected_edge_table(
    nodes_df,
    graph,
):
    tables = []

    for method in [
        "SP",
        "MST",
        "Steiner",
    ]:

        table = result_edge_table(
            nodes_df=
                nodes_df,
            graph=
                graph,
            method=
                method,
            edges=
                EXPECTED[
                    method
                ][
                    "edges"
                ],
        )

        tables.append(
            table
        )

    return pd.concat(
        tables,
        ignore_index=True,
    )


