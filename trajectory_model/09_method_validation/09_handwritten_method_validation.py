def normalized_edge(u, v):
    u = int(u)
    v = int(v)
    return tuple(
        sorted(
            (u, v)
        )
    )


def recover_path(predecessors, source, target, n_nodes):
    source = int(source)
    current = int(target)

    path = [current]

    steps = 0

    while current != source:

        previous = int(
            predecessors[current]
        )

        if (
            previous == NO_PREDECESSOR
            or previous < 0
        ):
            raise RuntimeError(
                f"No predecessor while tracing "
                f"{source} -> {target}"
            )

        current = previous

        path.append(
            current
        )

        steps += 1

        if steps > n_nodes:
            raise RuntimeError(
                "Predecessor loop detected."
            )

    path.reverse()

    return path


def edges_from_path(path):
    return {
        normalized_edge(
            u,
            v,
        )
        for u, v in zip(
            path[:-1],
            path[1:],
        )
    }


def edge_weight(graph, edge):
    u, v = edge

    return float(
        graph[
            int(u),
            int(v),
        ]
    )


def total_edge_weight(graph, edges):
    return float(
        sum(
            edge_weight(
                graph,
                edge,
            )
            for edge in edges
        )
    )


def node_names(nodes_df, nodes):
    mapping = dict(
        zip(
            nodes_df["node_index"],
            nodes_df["node"],
        )
    )

    return [
        mapping[int(x)]
        for x in sorted(nodes)
    ]


def edge_names(nodes_df, edges):
    mapping = dict(
        zip(
            nodes_df["node_index"],
            nodes_df["node"],
        )
    )

    return [
        f"{mapping[int(u)]}-{mapping[int(v)]}"
        for u, v in sorted(edges)
    ]


def jaccard(a, b):
    a = set(a)
    b = set(b)

    if not a and not b:
        return 1.0

    union = a | b

    if not union:
        return 1.0

    return len(
        a & b
    ) / len(
        union
    )


def build_sparse_graph(nodes_df, edges_df):
    n = len(
        nodes_df
    )

    rows = []
    cols = []
    data = []

    for row in edges_df.itertuples(
        index=False
    ):

        u = int(
            row.node_u
        )

        v = int(
            row.node_v
        )

        w = float(
            row.weight
        )

        rows.extend(
            [u, v]
        )

        cols.extend(
            [v, u]
        )

        data.extend(
            [w, w]
        )

    graph = sp.csr_matrix(
        (
            data,
            (
                rows,
                cols,
            ),
        ),
        shape=(
            n,
            n,
        ),
    )

    graph.sort_indices()

    return graph


