# METHOD 2 — MST ON INDUCED CANDIDATE GRAPH
# Mirrors Step 05.
# ======================================================================

def run_mst(
    full_graph,
    candidate,
):
    candidate_global = candidate[
        "global"
    ]

    H = candidate[
        "graph"
    ]

    mst_local = minimum_spanning_tree(
        H
    ).tocoo()

    if mst_local.nnz != len(
        candidate_global
    ) - 1:

        raise RuntimeError(
            "Toy MST does not have |V|-1 edges."
        )

    final_edges = set()

    for local_u, local_v in zip(
        mst_local.row,
        mst_local.col,
    ):

        global_u = int(
            candidate_global[
                int(
                    local_u
                )
            ]
        )

        global_v = int(
            candidate_global[
                int(
                    local_v
                )
            ]
        )

        final_edges.add(
            normalized_edge(
                global_u,
                global_v,
            )
        )

    final_nodes = set(
        map(
            int,
            candidate_global,
        )
    )

    return {
        "nodes":
            final_nodes,
        "edges":
            final_edges,
        "weight":
            total_edge_weight(
                full_graph,
                final_edges,
            ),
    }


# ======================================================================
# KMB PRUNING
# Mirrors Step 06.
# ======================================================================

def prune_nonterminal_leaves(
    n_local,
    edge_pairs,
    terminal_local_set,
):
    adjacency = {
        i: set()
        for i in range(
            n_local
        )
    }

    for u, v in edge_pairs:
        adjacency[
            int(u)
        ].add(
            int(v)
        )

        adjacency[
            int(v)
        ].add(
            int(u)
        )

    active = set()

    for u, v in edge_pairs:
        active.add(
            int(u)
        )

        active.add(
            int(v)
        )

    active.update(
        terminal_local_set
    )

    queue = deque(
        node
        for node in active
        if (
            node not in terminal_local_set
            and len(
                adjacency[
                    node
                ]
            ) <= 1
        )
    )

    while queue:

        node = queue.popleft()

        if node not in active:
            continue

        if node in terminal_local_set:
            continue

        if len(
            adjacency[
                node
            ]
        ) > 1:
            continue

        neighbors = list(
            adjacency[
                node
            ]
        )

        if len(
            neighbors
        ) == 1:

            neighbor = neighbors[
                0
            ]

            adjacency[
                neighbor
            ].remove(
                node
            )

            adjacency[
                node
            ].clear()

            if (
                neighbor
                not in terminal_local_set
                and len(
                    adjacency[
                        neighbor
                    ]
                ) <= 1
            ):
                queue.append(
                    neighbor
                )

        active.remove(
            node
        )

    remaining_edges = set()

    for u in active:

        for v in adjacency[
            u
        ]:

            if (
                v in active
                and u < v
            ):
                remaining_edges.add(
                    (
                        int(u),
                        int(v),
                    )
                )

    return (
        active,
        remaining_edges,
    )


# ======================================================================
# METHOD 3 — KMB-STYLE STEINER APPROXIMATION
# Mirrors Step 06.
# ======================================================================

def run_steiner(
    full_graph,
    candidate,
    anchors,
):
    candidate_global = candidate[
        "global"
    ]

    H = candidate[
        "graph"
    ]

    n_candidate = len(
        candidate_global
    )

    global_to_local = {
        int(global_node):
            int(local_node)
        for local_node, global_node
        in enumerate(
            candidate_global
        )
    }

    terminal_local = np.array(
        [
            global_to_local[
                int(node)
            ]
            for node in anchors
        ],
        dtype=np.int64,
    )

    terminal_set_local = set(
        map(
            int,
            terminal_local,
        )
    )

    # KMB Step 1:
    # shortest-path metric among terminals.
    distances, predecessors = dijkstra(
        H,
        directed=False,
        indices=terminal_local,
        return_predecessors=True,
    )

    terminal_metric = distances[
        :,
        terminal_local
    ]

    if not np.isfinite(
        terminal_metric
    ).all():

        raise RuntimeError(
            "Non-finite terminal metric."
        )

    # KMB Step 2:
    # MST of complete terminal metric closure.
    metric_sparse = sp.csr_matrix(
        terminal_metric
    )

    metric_mst = minimum_spanning_tree(
        metric_sparse
    ).tocoo()

    if metric_mst.nnz != len(
        anchors
    ) - 1:

        raise RuntimeError(
            "Terminal metric MST failed."
        )

    metric_rows = []

    expanded_edges = set()

    expanded_nodes = set(
        terminal_set_local
    )

    # KMB Step 3:
    # expand terminal metric MST edges back to H_c.
    for terminal_u, terminal_v, metric_weight in zip(
        metric_mst.row,
        metric_mst.col,
        metric_mst.data,
    ):

        terminal_u = int(
            terminal_u
        )

        terminal_v = int(
            terminal_v
        )

        source_local = int(
            terminal_local[
                terminal_u
            ]
        )

        target_local = int(
            terminal_local[
                terminal_v
            ]
        )

        path = recover_path(
            predecessors=
                predecessors[
                    terminal_u
                ],
            source=
                source_local,
            target=
                target_local,
            n_nodes=
                n_candidate,
        )

        expanded_nodes.update(
            path
        )

        for left, right in zip(
            path[:-1],
            path[1:],
        ):

            expanded_edges.add(
                normalized_edge(
                    left,
                    right,
                )
            )

        metric_rows.append(
            {
                "terminal_u_global":
                    int(
                        candidate_global[
                            source_local
                        ]
                    ),
                "terminal_v_global":
                    int(
                        candidate_global[
                            target_local
                        ]
                    ),
                "metric_distance":
                    float(
                        metric_weight
                    ),
                "expanded_path_global":
                    "|".join(
                        str(
                            int(
                                candidate_global[
                                    int(x)
                                ]
                            )
                        )
                        for x in path
                    ),
            }
        )

    # Build expanded original-edge graph Q_c.
    q_rows = []
    q_cols = []
    q_data = []

    for u, v in sorted(
        expanded_edges
    ):

        weight = float(
            H[
                int(u),
                int(v),
            ]
        )

        q_rows.extend(
            [u, v]
        )

        q_cols.extend(
            [v, u]
        )

        q_data.extend(
            [weight, weight]
        )

    Q = sp.csr_matrix(
        (
            q_data,
            (
                q_rows,
                q_cols,
            ),
        ),
        shape=(
            n_candidate,
            n_candidate,
        ),
    )

    # KMB Step 4:
    # MST of expanded union.
    expanded_mst = minimum_spanning_tree(
        Q
    ).tocoo()

    tree_edges = {
        normalized_edge(
            u,
            v,
        )
        for u, v in zip(
            expanded_mst.row,
            expanded_mst.col,
        )
    }

    # KMB Step 5:
    # remove nonterminal leaves.
    (
        final_local_nodes,
        final_local_edges,
    ) = prune_nonterminal_leaves(
        n_local=
            n_candidate,
        edge_pairs=
            tree_edges,
        terminal_local_set=
            terminal_set_local,
    )

    if not terminal_set_local.issubset(
        final_local_nodes
    ):
        raise RuntimeError(
            "Steiner pruning removed a terminal."
        )

    final_nodes = {
        int(
            candidate_global[
                int(local_node)
            ]
        )
        for local_node
        in final_local_nodes
    }

    final_edges = {
        normalized_edge(
            int(
                candidate_global[
                    int(local_u)
                ]
            ),
            int(
                candidate_global[
                    int(local_v)
                ]
            ),
        )
        for local_u, local_v
        in final_local_edges
    }

    return {
        "nodes":
            final_nodes,
        "edges":
            final_edges,
        "weight":
            total_edge_weight(
                full_graph,
                final_edges,
            ),
        "terminal_metric":
            terminal_metric,
        "metric_mst":
            pd.DataFrame(
                metric_rows
            ),
    }


