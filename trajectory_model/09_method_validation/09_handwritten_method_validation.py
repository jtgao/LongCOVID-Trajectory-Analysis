# METHOD 1 — ROOTED SHORTEST-PATH UNION
# Mirrors Step 04.
# ======================================================================

def run_rooted_shortest_path(
    graph,
    nodes_df,
    anchors,
):
    anchor_meta = (
        nodes_df[
            nodes_df[
                "node_index"
            ].isin(
                anchors
            )
        ]
        .sort_values(
            [
                "time_month",
                "node_index",
            ]
        )
    )

    root = int(
        anchor_meta.iloc[
            0
        ][
            "node_index"
        ]
    )

    distances, predecessors = dijkstra(
        graph,
        directed=False,
        indices=root,
        return_predecessors=True,
    )

    final_nodes = {
        root
    }

    final_edges = set()

    path_rows = []

    for target in anchors:

        target = int(
            target
        )

        if target == root:
            continue

        path = recover_path(
            predecessors=
                predecessors,
            source=
                root,
            target=
                target,
            n_nodes=
                graph.shape[
                    0
                ],
        )

        path_edges = edges_from_path(
            path
        )

        final_nodes.update(
            path
        )

        final_edges.update(
            path_edges
        )

        path_rows.append(
            {
                "source":
                    root,
                "target":
                    target,
                "path_nodes":
                    "|".join(
                        map(
                            str,
                            path,
                        )
                    ),
                "distance":
                    float(
                        distances[
                            target
                        ]
                    ),
            }
        )

    return {
        "root":
            root,
        "nodes":
            final_nodes,
        "edges":
            final_edges,
        "weight":
            total_edge_weight(
                graph,
                final_edges,
            ),
        "paths":
            pd.DataFrame(
                path_rows
            ),
    }


# ======================================================================
# SHARED MST / STEINER CANDIDATE GRAPH
# Mirrors Step 05 candidate construction:
# union one shortest path for each unordered anchor pair, then take the
# induced subgraph on that candidate vertex set.
# ======================================================================

def build_candidate_graph(
    graph,
    anchors,
):
    anchors = np.array(
        sorted(
            map(
                int,
                anchors,
            )
        ),
        dtype=np.int64,
    )

    candidate_nodes = set(
        map(
            int,
            anchors,
        )
    )

    pair_rows = []

    k = len(
        anchors
    )

    for source_position in range(
        k - 1
    ):

        source = int(
            anchors[
                source_position
            ]
        )

        distances, predecessors = dijkstra(
            graph,
            directed=False,
            indices=source,
            return_predecessors=True,
        )

        for target in anchors[
            source_position + 1:
        ]:

            target = int(
                target
            )

            path = recover_path(
                predecessors=
                    predecessors,
                source=
                    source,
                target=
                    target,
                n_nodes=
                    graph.shape[
                        0
                    ],
            )

            candidate_nodes.update(
                path
            )

            pair_rows.append(
                {
                    "source":
                        source,
                    "target":
                        target,
                    "path_nodes":
                        "|".join(
                            map(
                                str,
                                path,
                            )
                        ),
                    "distance":
                        float(
                            distances[
                                target
                            ]
                        ),
                }
            )

    candidate_global = np.array(
        sorted(
            candidate_nodes
        ),
        dtype=np.int64,
    )

    candidate_graph = graph[
        candidate_global
    ][
        :,
        candidate_global
    ].tocsr()

    candidate_graph.sort_indices()

    n_components, _ = connected_components(
        candidate_graph,
        directed=False,
        return_labels=True,
    )

    if n_components != 1:
        raise RuntimeError(
            "Toy candidate graph is disconnected."
        )

    return {
        "nodes":
            set(
                map(
                    int,
                    candidate_global,
                )
            ),
        "global":
            candidate_global,
        "graph":
            candidate_graph,
        "pair_paths":
            pd.DataFrame(
                pair_rows
            ),
    }


